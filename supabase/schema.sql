    create policy "Admins can update spots"
    on public.spots
    for update
    using (
      exists (
        select 1
        from public.profiles p
        where p.user_id = auth.uid() and p.role = 'admin'
      )
    )
    with check (
      exists (
        select 1
        from public.profiles p
        where p.user_id = auth.uid() and p.role = 'admin'
      )
    );
  end if;
end $$;

do $$
